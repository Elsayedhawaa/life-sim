import assert from 'node:assert/strict';
import { createNewLifeState, ensureExtendedState } from '../src/core/schema.js';
import { snapshotTurn, buildTurnResult, renderTurnResultCardHtml } from '../src/ui/turnResult.js';
import { renderLifeTabHtml } from '../src/ui/views.js';
const s=createNewLifeState({seed:9,country:'jpn'});
ensureExtendedState(s);s.player.age=25;s.year=2023;
const before=snapshotTurn(s), mom=s.people[s.relations.motherId];
s.skills.creativity+=3;mom.rel.trust+=5;
const result=buildTurnResult(s,before,'choice');
assert.equal(result.skillDeltas.find(x=>x.label==='Creativity').delta,3);
assert.equal(result.relationshipDeltas.find(x=>x.label.includes('trust')).delta,5);
const html=renderTurnResultCardHtml(s,{turnResult:result});
assert.ok(html.includes('Creativity +3'));
assert.ok(html.includes('trust +5'));
s.activeScene={title:'One decision',text:'A test',choices:[{label:'Answer',effect:()=>{}}]};
const view=renderLifeTabHtml(s);
assert.ok(view.includes('decision-focus'));
assert.ok(!view.includes('Daily Routines'));
assert.ok(!view.includes('journalQuery'));
assert.ok(view.includes('Your life at a glance'));
console.log('Passed result feedback and decision-focus rendering tests.');
